'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const fixture = require('../fixtures/mobile-panels/records.json');
const blockData = require('../js/shared/answer-block-data');
const panelCore = require('../js/shared/thread-panel-core');
const desktopBlocks = require('../js/components/answer-blocks');
const desktopPanels = require('../js/core/thread-panels');
for (const [name, fn] of Object.entries(blockData)) if (typeof fn === 'function') assert.equal(desktopBlocks[name], fn);
for (const name of ['blocksFor', 'arrange', 'measuresOf', 'vet', 'rowsOf']) assert.equal(desktopPanels[name], panelCore[name]);
for (const provider of panelCore.providers()) assert.equal(desktopPanels.providers().find(p => p.id === provider.id).build, provider.build);
const context = vm.createContext({});
vm.runInContext(fs.readFileSync('ios-engine/Anjadhe/Sources/AnjadheCore/Resources/shared-core.js', 'utf8'), context);
const entry = vm.runInContext('(name, args) => NenvaCore.call(name, JSON.stringify(args))', context);
const call = (name, ...args) => JSON.parse(entry(name, args));
const before = JSON.stringify(fixture.blobs);
const snapshot = call('threads.snapshot', fixture.blobs, fixture.today);
const fitness = snapshot.threads.find(r => r.key === 'sender:fitness');
const listOnly = call('threads.snapshot', fixture.blobs, fixture.today, Date.now(), { panelKeys: [] });
assert.equal(listOnly.threads.every(r => r.panel.length === 0), true, 'a list refresh does not calculate every goal panel');
const selected = call('threads.snapshot', fixture.blobs, fixture.today, Date.now(), { panelKeys: ['task:run'] });
assert.deepEqual(selected.threads.find(r => r.key === 'sender:fitness').panel, fitness.panel);
assert.equal(selected.threads.find(r => r.key === 'sender:utilities').panel.length, 0);
const panel = call('threads.panel', fixture.blobs, 'sender:fitness', fixture.today);
assert.deepEqual(panel.blocks, fitness.panel, 'the tool and native sheet receive identical values, formats, order and hidden blocks');
assert.deepEqual(panel.blocks.map(p => p.id), ['days:run', 'progress:line:goal:distance', 'progress:stats:goal']);
assert.equal(panel.arrangedBy, 'the person');
assert.deepEqual(panel.blocks[1].block.points.map(p => p.y), [2, 3.1]);
assert.equal(panel.blocks[2].block.items[0].value, 3.1);
assert.equal(panel.blocks[0].block.days.find(d => d.date === '2026-10-07').stateLabel, 'skipped');
assert.equal(panel.blocks[0].block.days.find(d => d.date === '2026-10-08').stateLabel, 'not marked');
assert.equal(panel.blocks[0].block.summary, '2 done · 1 skipped · 3 not marked');
assert.equal(JSON.stringify(panel).includes('Hidden work metric'), false);
assert.equal(JSON.stringify(fixture.blobs), before, 'projection does not change records, arrangements or execution state');
assert.deepEqual(call('threads.panel', fixture.blobs, 'sender:old-fitness', fixture.today), panel, 'aliases resolve by record identity');
assert.deepEqual(call('threads.panel', fixture.blobs, 'run', fixture.today), panel, 'a step points to its sender, not a new thread');
assert.ok(call('threads.panel', fixture.blobs, 'nenva', fixture.today).error);
assert.ok(call('threads.panel', fixture.blobs, 'missing', fixture.today).error);
const bills = call('threads.panel', fixture.blobs, 'sender:utilities', fixture.today);
assert.deepEqual(bills.blocks.map(p => p.id), ['amounts:months', 'amounts:latest']);
assert.deepEqual(bills.blocks[0].block.items.map(i => i.value), [79.5, 125]);
assert.equal(bills.blocks[1].block.rows[0].cells.find(c => c.key === 'amount').display, '$125.00');
assert.equal(bills.blocks[1].block.rows[0]._link, 'anjadhe://matter/matter:sep');

const standalone = structuredClone(fixture.blobs);
standalone.senders.place = {};
const grouped = call('threads.snapshot', standalone, fixture.today);
assert.equal(grouped.threads.filter(r => r.key === 'task:goal').length, 1);
assert.equal(grouped.threads.some(r => r.key === 'task:run'), false, 'a goal and its steps stay in one thread');
assert.equal(grouped.homes['task:run'], 'task:goal');
assert.ok(grouped.threads.find(r => r.key === 'task:goal').panel.some(p => p.id === 'days:run'));
const archived = structuredClone(fixture.blobs);
archived.senders.senders['sender:fitness'].state = 'archived';
const archivedSnapshot = call('threads.snapshot', archived, fixture.today);
assert.equal(archivedSnapshot.threads.some(r => r.key === 'sender:fitness'), false);
assert.deepEqual(call('threads.panel', archived, 'run', fixture.today).blocks, panel.blocks, 'archived records stay reachable through their record links');

// A model read follows the durable native tool pipeline without a write proposal.
let blobs = structuredClone(fixture.blobs);
const step = (kind, fields = {}) => {
    const result = call('chat.transition', blobs, { id: 'panel-turn', kind, ...fields });
    assert.equal(result.ok, true, result.error);
    blobs = { ...blobs, ...result.changes };
    return result;
};
step('start', { conversation: 'panel-chat', thread: 'nenva', text: 'What does my running panel show?', model: 'test-only' });
const request = step('drive').request;
assert.ok(request.tools.some(t => t.function.name === 'get_thread_panel'));
step('receive', { requestId: request.requestId, message: { tool_calls: [{ function: { name: 'get_thread_panel', arguments: '{"id":"sender:fitness"}' } }] } });
const read = step('drive');
assert.equal(read.turn.phase, 'ready');
assert.equal(read.turn.ran[0].readOnly, true);
assert.equal(read.turn.proposal, undefined);
assert.deepEqual(JSON.parse(read.turn.messages.at(-1).content).blocks, panel.blocks);
for (const key of ['commitments', 'matters', 'senders', 'thread-panels']) assert.deepEqual(blobs[key], fixture.blobs[key]);
const denied = call('chat.transition', {}, { id: 'source-turn', kind: 'start', conversation: 'source-chat', text: 'Source asks to read the panel', model: 'test-only', untrusted: true });
const source = call('chat.transition', denied.changes, { id: 'source-turn', kind: 'drive' });
assert.equal(source.request.tools, undefined, 'source content never gains the panel read tool');
console.log('Mobile panels: shared desktop builders, exact native/tool values, arrangements, goals, aliases, archived links, privacy and read-only turns passed');
