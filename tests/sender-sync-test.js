'use strict';
const assert = require('node:assert/strict');
const S = require('../js/shared/sender-sync');
const M = require('../js/sync/record-merge');
const empty = { senders: {}, place: {} };
assert.equal(S.id('dental\n'), false);
assert.equal(S.validField('sender-placement', 'placement', { sender: 'dental\n', by: 'you', at: 'today' }), false);
const sender = (id, name) => ({ id, name, allGood: 'Everything is current.', state: 'active', confirmed: true, by: 'you', createdAt: '2026-10-12', updatedAt: '2026-10-12' });
const initial = { version: 1, senders: { dental: sender('dental', 'Your dental'), music: sender('music', 'Music classes') }, place: { 'task:visit': { sender: 'dental', by: 'you', at: '2026-10-12' } }, tries: { local: 'LOCAL_ONLY' }, aliases: {} };
const plan = S.plan(empty, initial);
assert.equal(plan.mutations.length, 3);
assert.doesNotMatch(JSON.stringify(plan.mutations), /LOCAL_ONLY|updatedAt/);
const operation = (deviceId, sequence, dependencies, type, id, fields) => ({ protocolVersion: 2, schemaVersion: 1, datasetId: 'fixture', membershipEpoch: 1, deviceId, sequence, dependencies, recordType: type, recordId: id, mutation: { kind: 'edit', fields } });
const ops = plan.mutations.map((m, i) => operation('a', i + 1, i ? { a: i } : {}, m.type, m.id, m.mutation.fields));
const records = M.reduce(ops, 'fixture').records;
assert.deepEqual(S.plan(initial, initial, records).mutations, []);
assert.throws(() => S.plan(initial, initial, []), /bootstrap/);
assert.throws(() => S.plan(empty, initial, records), /collision/);
const change = fn => { const copy = structuredClone(initial); fn(copy); return copy; };
assert.throws(() => S.plan(initial, change(c => delete c.senders.music), records), /Missing sender history/);
assert.throws(() => S.plan(initial, change(c => delete c.place['task:visit']), records), /Missing sender history/);
assert.throws(() => S.plan(initial, change(c => c.place['task:visit'].by = 'nenva'), records), /personal choice/);
assert.throws(() => S.plan(initial, change(c => c.senders.dental.createdAt = 'changed'), records), /creation identity/);
assert.throws(() => S.plan(initial, change(c => c.aliases.old = 'dental'), records), /migration/);
assert.throws(() => S.plan(initial, change(c => c.senders.dental.facts = [{ text: 'important' }]), records), /migration/);
assert.throws(() => S.plan(initial, change(c => c.threadSeen = { dental: 'today' }), records), /migration/);
assert.throws(() => S.plan(initial, change(c => delete c.senders.dental.name), records), /wire fields/);
assert.throws(() => S.plan(initial, change(c => c.place['task:visit'].sender = 'missing'), records), /target/);
const clear = S.plan(initial, change(c => c.place['task:visit'] = null), records);
assert.deepEqual(clear.mutations[0].mutation.fields, { placement: null });
const renamed = operation('b', 1, { a: 3 }, 'sender', 'dental', { name: 'Our dental' });
const purpose = operation('c', 1, { a: 3 }, 'sender', 'dental', { allGood: 'Healthy teeth.' });
const merged = M.reduce([...ops, purpose, renamed], 'fixture');
assert.equal(merged.records.find(r => r.id === 'dental').conflicts.fields.length, 0);
assert.equal(S.project(merged.records).senders.dental.name, 'Our dental');
assert.equal(S.project(merged.records).senders.dental.allGood, 'Healthy teeth.');
assert.throws(() => S.plan(initial, initial, merged.records), /conflict review/);
const move = operation('b', 1, { a: 3 }, 'sender-placement', 'task:visit', { placement: { sender: 'music', by: 'you', at: '2026-10-12' } });
const unmove = operation('c', 1, { a: 3 }, 'sender-placement', 'task:visit', { placement: null });
const disputed = S.project(M.reduce([...ops, move, unmove], 'fixture').records);
assert.equal(disputed.placements[0].versions.length, 2);
assert.equal(disputed.placements[0].needsReview, true);
assert.equal(Object.hasOwn(disputed.place, 'task:visit'), false, 'No automatic conflict winner becomes a home');
const missing = S.project(records.filter(r => r.id !== 'dental'));
assert.deepEqual(missing.placements[0].missingTargets, ['dental']);
assert.equal(Object.hasOwn(missing.place, 'task:visit'), false);
// Record ids are opaque; a JS prototype name must not act as a phantom target.
const proto = S.project([M.reduce([operation('a', 1, {}, 'sender-placement', 'item', { placement: { sender: '__proto__', by: 'you', at: 'today' } })], 'fixture').records[0]]);
assert.deepEqual(proto.placements[0].missingTargets, ['__proto__']);
const big = { senders: Object.fromEntries(Array.from({ length: 257 }, (_, i) => ['s'+i, sender('s'+i, 'Thread')])), place: {} };
assert.throws(() => S.plan(empty, big), /paged migration/);
console.log('Sender sync: independent edits, disputed moves, missing targets, archive gates and local-only caches passed');
