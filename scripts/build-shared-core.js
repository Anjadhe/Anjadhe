#!/usr/bin/env node
'use strict';
// Reproducible source bundle. Desktop loads these same files directly.
// --check is part of npm test so stale native resources cannot pass CI.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const sources = ['js/shared/commitment-calendar.js', 'js/shared/thread-core.js', 'js/shared/sender-membership.js', 'js/shared/commitments-records.js', 'js/shared/senders-records.js', 'js/core/sender-kinds.js', 'js/shared/matters-records.js', 'js/shared/mobile-records.js', 'js/shared/record-transaction.js', 'js/shared/claim-check.js', 'js/shared/chat-prompt.js', 'js/shared/commitment-tool-contract.js', 'js/shared/matter-capture.js', 'js/shared/occurrence-capture.js', 'js/shared/thing-capture.js', 'js/shared/source-intake.js', 'js/shared/chat-turn.js', 'js/shared/conversation-sync.js', 'js/shared/sender-sync.js', 'js/shared/native-entry.js'];
const output = path.join(root, 'ios-engine/Anjadhe/Sources/AnjadheCore/Resources/shared-core.js');
const bundle = '// Generated by scripts/build-shared-core.js. Edit js/shared/, then regenerate.\n' +
    sources.map(file => `\n// Source: ${file}\n${fs.readFileSync(path.join(root, file), 'utf8')}`).join('');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== bundle) {
        console.error('Shared native core is stale. Run npm run build:shared-core.'); process.exitCode = 1;
    } else console.log('Shared native core matches desktop sources');
} else {
    fs.mkdirSync(path.dirname(output), { recursive: true }); fs.writeFileSync(output, bundle);
    console.log('Built ' + path.relative(root, output));
}
