import XCTest
@testable import AnjadheCore

final class SharedCoreTests: XCTestCase {
    func testBundledResourceIsExactlyTheDesktopSource() throws {
        var root = URL(fileURLWithPath: #filePath)
        for _ in 0..<5 { root.deleteLastPathComponent() }
        let files = ["js/shared/commitment-calendar.js", "js/shared/thread-core.js", "js/shared/sender-membership.js", "js/shared/commitments-records.js", "js/shared/senders-records.js", "js/core/sender-kinds.js", "js/shared/matters-records.js", "js/shared/mobile-records.js", "js/shared/record-transaction.js", "js/shared/claim-check.js", "js/shared/chat-prompt.js", "js/shared/commitment-tool-contract.js", "js/shared/matter-capture.js", "js/shared/occurrence-capture.js", "js/shared/thing-capture.js", "js/shared/source-intake.js", "js/shared/chat-turn.js", "js/shared/conversation-sync.js", "js/shared/sender-sync.js", "js/shared/native-entry.js"]
        var expected = "// Generated by scripts/build-shared-core.js. Edit js/shared/, then regenerate.\n"
        for file in files {
            expected += "\n// Source: \(file)\n" + (try String(contentsOf: root.appendingPathComponent(file), encoding: .utf8))
        }
        let bundled = try String(contentsOf: XCTUnwrap(SharedCore.resourceURL), encoding: .utf8)
        XCTAssertEqual(Data(bundled.utf8), Data(expected.utf8))
    }

    func testTimelineRunsDesktopRulesInJavaScriptCore() async throws {
        let core = SharedCore()
        let matter = try JSONValue.parse(#"{"id":"m1","state":"open","sources":[{"id":"e1","from":"School","at":"2026-10-11T10:00:00Z","summary":"Pay by Friday"}],"log":[]}"#)
        let conversation = try JSONValue.parse(#"{"messages":[{"role":"user","content":"paid it","timestamp":"2026-10-11T12:00:00Z"},{"role":"assistant","content":"Kept **தமிழ் café**. \"; globalThis.injected=true; //","timestamp":"2026-10-11T11:00:00Z"},{"role":"tool","content":"hidden"}]}"#)
        let items = try await core.call(.timeline, arguments: [matter, conversation])
        let rows = try XCTUnwrap(items.arrayValue)
        XCTAssertEqual(rows.count, 3)
        XCTAssertEqual(rows[0]["text"], .string("School emailed. Pay by Friday."))
        XCTAssertEqual(rows[1]["at"], rows[2]["at"], "A reply never jumps above its question")
        XCTAssertEqual(rows[1]["side"], .string("me"))
        let preview = try await core.call(.preview, arguments: [items])
        XCTAssertTrue(preview.stringValue?.hasPrefix("Kept தமிழ் café.") == true)
        let copy = try await core.call(.copy)
        XCTAssertTrue(copy["welcome"]?.stringValue?.hasPrefix("Hi, I’m nenva.") == true)
    }

    func testSenderIntroAndInfoUseSharedCode() async throws {
        let core = SharedCore()
        let sender = try JSONValue.parse(#"{"id":"sender:auto","name":"Auto insurance","allGood":"Covered and paid","confirmed":false,"createdAt":"2026-10-11T10:00:00Z"}"#)
        let members = try JSONValue.parse(#"[{"key":"matter:renewal","type":"matter","title":"Renewal","settled":false,"at":1,"items":[{"at":1,"kind":"message","side":"them","text":"GEICO emailed."}],"rec":{"when":{"date":"2026-11-02"},"amount":"$612","code":"P-77"}}]"#)
        let timeline = try await core.call(.senderTimeline, arguments: [sender, members])
        XCTAssertEqual(timeline.arrayValue?.first?["kind"], .string("intro"))
        XCTAssertEqual(timeline.arrayValue?.first?["text"], .string("I started keeping track of Auto insurance for you. All good means: Covered and paid."))
        let info = try await core.call(.senderInfo, arguments: [members, .string("2026-10-11")])
        XCTAssertEqual(info["upcoming"]?.arrayValue?.first?["date"], .string("2026-11-02"))
        XCTAssertEqual(info["facts"]?.arrayValue?.count, 2)
    }

    func testRecurrenceAndDayMoveUseTheDesktopCalendar() async throws {
        let core = SharedCore()
        let monthly = try JSONValue.parse(#"{"when":{"date":"2026-01-31"},"repeat":{"rule":"monthly"}}"#)
        let next = try await core.call(.nextOn, arguments: [monthly, .string("2026-02-01")])
        XCTAssertEqual(next, .string("2026-02-28"))
        let moved = try JSONValue.parse(#"{"when":{"time":"09:00"},"repeat":{"rule":"daily"},"moved":{"2026-10-11":{"time":"15:00"}},"history":{"2026-10-11":"done"}}"#)
        let time = try await core.call(.timeOn, arguments: [moved, .string("2026-10-11")])
        XCTAssertEqual(time["time"], .string("15:00"))
        let following = try await core.call(.timeOn, arguments: [moved, .string("2026-10-12")])
        XCTAssertEqual(following["time"], .string("09:00"))
        let done = try await core.call(.isDone, arguments: [moved, .string("2026-10-11")])
        XCTAssertEqual(done, .bool(true))
    }

    func testFailureIsSanitizedAndDoesNotPoisonNextCall() async throws {
        let core = SharedCore()
        do {
            _ = try await core.call(.senderTimeline, arguments: [.null, .string("private record content")])
            XCTFail("Malformed records must fail visibly")
        } catch { XCTAssertEqual(error as? SharedCore.Failure, .executionFailed) }
        let valid = try await core.call(.day, arguments: [.string("2026-10-11")])
        XCTAssertEqual(valid, .string("2026-10-11"))
        do {
            _ = try await core.call(.copy, arguments: [.string(String(repeating: "x", count: SharedCore.maximumPayloadBytes))])
            XCTFail("Oversized input must be rejected")
        } catch { XCTAssertEqual(error as? SharedCore.Failure, .payloadTooLarge) }
        do {
            _ = try await core.call(.today, arguments: [.number(.nan)])
            XCTFail("Non-JSON numbers must fail")
        } catch { XCTAssertEqual(error as? SharedCore.Failure, .invalidArguments) }
    }

    func testSharedClaimCheckRefusesUnsupportedSuccessAndKeepsItsPrompt() async throws {
        let core = SharedCore()
        let raw = try JSONValue.parse(#"{"claims":[{"text":"I added the task.","kind":"did"}]}"#)
        let result = try await core.call(.claimVet, arguments: [raw, .string("I added the task."), .object(["ran": .array([])])])
        XCTAssertEqual(result["unbacked"]?.arrayValue, [.string("I added the task.")])
        let prompt = try await core.call(.claimPrompt, arguments: [.object(["reply": .string("I added the task."), "userText": .string("Add a task")])])
        XCTAssertTrue(prompt.stringValue?.contains("copied word for word from REPLY") == true)
        let look = try await core.call(.claimWorthLooking, arguments: [.object(["reply": .string("I added the task."), "canWrite": .bool(true)])])
        XCTAssertEqual(look, .bool(true))
    }

    func testCaptureUsesDesktopChecksInJavaScriptCore() async throws {
        let core = SharedCore()
        let record = try JSONValue.parse(#"{"id":"walk","title":"Walk","state":"open","repeat":{"rule":"none"},"history":{}}"#)
        let input: JSONValue = .object(["commitments": .object(["items": .array([record])])])
        let raw = try JSONValue.parse(#"{"record":"done","report":"done","quote":"I did it","card":"gone"}"#)
        let checked = try await core.call(.captureInspect, arguments: [input, .string("task"), record, .string("I did it"), raw])
        XCTAssertEqual(checked["plan"]?["record"]?["door"], .string("report"))
        XCTAssertEqual(checked["plan"]?["record"]?["j"]?["quote"], .string("I did it"))
        let rejected = try await core.call(.captureInspect, arguments: [input, .string("task"), record, .string("How do I start?"), raw])
        XCTAssertEqual(rejected["plan"]?["record"], .null)
    }

    func testConcurrentCallersAndCancellation() async throws {
        let core = SharedCore()
        try await withThrowingTaskGroup(of: JSONValue.self) { group in
            for _ in 0..<24 {
                group.addTask { try await core.call(.day, arguments: [.string("2026-10-11")]) }
            }
            for try await result in group { XCTAssertEqual(result, .string("2026-10-11")) }
        }
        let canceled = Task {
            withUnsafeCurrentTask { $0?.cancel() }
            return try await core.call(.copy)
        }
        do { _ = try await canceled.value; XCTFail("Canceled work must not enter the core") }
        catch { XCTAssertTrue(error is CancellationError) }
    }
}
